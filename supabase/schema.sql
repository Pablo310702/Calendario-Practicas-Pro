-- Ejecuta este script en Supabase > SQL Editor.
-- La RLS garantiza que cada estudiante solo pueda leer y modificar su propio plan.

create table if not exists public.practice_plans (
  user_id uuid primary key references auth.users(id) on delete cascade,
  plan_name text not null default 'Plan de prácticas',
  state jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.usage_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_name text not null check (event_name in ('signup','login','sync','export')),
  created_at timestamptz not null default now()
);

alter table public.practice_plans enable row level security;
alter table public.usage_events enable row level security;

drop policy if exists "Students manage their own plan" on public.practice_plans;
create policy "Students manage their own plan" on public.practice_plans
  for all to authenticated using (auth.uid() = user_id) with check (auth.uid() = user_id);

drop policy if exists "Students can create usage events" on public.usage_events;
create policy "Students can create usage events" on public.usage_events
  for insert to authenticated with check (auth.uid() = user_id);

drop policy if exists "Students can read their usage events" on public.usage_events;
create policy "Students can read their usage events" on public.usage_events
  for select to authenticated using (auth.uid() = user_id);

create or replace function public.register_usage(event_name text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    raise exception 'not authenticated';
  end if;
  insert into public.usage_events(user_id,event_name) values (auth.uid(),event_name);
end;
$$;

revoke all on function public.register_usage(text) from public;
grant execute on function public.register_usage(text) to authenticated;
